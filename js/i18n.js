export function language() {
    const user = read('currentUser'),
        all = read('settings', {});
    return (all.byUser?.[user?.id || 'guest']?.language || all.language) === 'en' ? 'en' : 'vi';
}
export const locale = () => (language() === 'en' ? 'en-US' : 'vi-VN');
export function t(key, values = {}) {
    let text = dictionary[language()]?.[key] ?? dictionary.vi[key] ?? key;
    for (const [name, value] of Object.entries(values))
        text = text.replaceAll('{' + name + '}', String(value));
    return text;
}
export function localized(item, field) {
    return (language() === 'en' && item?.[field + '_en']) || item?.[field] || '';
}
export function applyTranslations(root = document) {
    document.documentElement.lang = language();
    for (const [attribute, target] of [
        ['data-i18n', 'textContent'],
        ['data-i18n-placeholder', 'placeholder'],
        ['data-i18n-aria-label', 'aria-label'],
        ['data-i18n-content', 'content']
    ]) {
        root.querySelectorAll('[' + attribute + ']').forEach((el) => {
            const text = t(el.getAttribute(attribute));
            if (target === 'aria-label' || target === 'content') el.setAttribute(target, text);
            else if (el[target] !== text) el[target] = text;
        });
    }
    if (document.body.dataset.screen === 'S1') document.title = t('home.title') + ' · EventPulse';
}
